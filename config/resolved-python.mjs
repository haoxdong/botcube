import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const source = fileURLToPath(new URL('./resolved.ts', import.meta.url));
const primitives = new Map([
  [ts.TypeFlags.String, 'str'],
  [ts.TypeFlags.TemplateLiteral, 'str'],
  [ts.TypeFlags.Number, 'int | float'],
  [ts.TypeFlags.Boolean, 'bool'],
  [ts.TypeFlags.Null, 'None'],
]);
const typeName = (key) => key.replace(/[^a-zA-Z0-9_]/g, '').replace(/^./, (initial) => initial.toUpperCase());

export function resolvedPython(version) {
  const program = ts.createProgram([source], {
    strict: true,
    exactOptionalPropertyTypes: true,
    module: ts.ModuleKind.NodeNext,
    target: ts.ScriptTarget.ES2022,
    skipLibCheck: true,
  });
  const checker = program.getTypeChecker();
  const file = program.getSourceFile(source);
  const declaration = file.statements.find((node) => ts.isTypeAliasDeclaration(node) && node.name.text === 'ResolvedConfig');
  const state = { checker, names: new Map(), definitions: new Map() };
  pythonType(checker.getTypeAtLocation(declaration), 'ResolvedConfig', state);
  return [
    '# Generated by pnpm --filter botcube-config emit.',
    'from typing import Literal, NotRequired, TypedDict',
    '',
    `FORMAT_VERSION = ${version}`,
    ...Array.from(state.definitions.values(), (definition) => `\n\n${definition}`),
  ].join('\n') + '\n';
}

function pythonType(type, name, state) {
  if (primitives.has(type.flags)) return primitives.get(type.flags);
  const value = pythonLiteral(type);
  if (value !== undefined) return `Literal[${value}]`;
  if (type.isUnion()) return pythonUnion(type.types, name, state);
  if (state.checker.isArrayType(type) || state.checker.isTupleType(type)) {
    const members = state.checker.getTypeArguments(type).map((member) => pythonType(member, `${name}Item`, state));
    return `list[${[...new Set(members)].join(' | ')}]`;
  }
  if (type.flags === ts.TypeFlags.Object || type.isIntersection()) return pythonObject(type, name, state);
  throw new Error(`Cannot emit Python type for ${name}: ${state.checker.typeToString(type)}`);
}

function pythonLiteral(type) {
  if (type.isLiteral()) return JSON.stringify(type.value);
  if (type.flags === ts.TypeFlags.BooleanLiteral) return type.intrinsicName === 'true' ? 'True' : 'False';
  return undefined;
}

function pythonUnion(types, name, state) {
  const members = types.filter((member) => member.flags !== ts.TypeFlags.Undefined && state.checker.typeToString(member) !== 'never');
  const literals = members.map(pythonLiteral).filter((value) => value !== undefined);
  const variants = members.filter((member) => pythonLiteral(member) === undefined)
    .map((member, index, all) => pythonType(member, all.length > 1 ? `${name}${index + 1}` : name, state));
  if (literals.length > 0) {
    variants.push(literals.length === 2 && literals.includes('False') && literals.includes('True') ? 'bool' : `Literal[${literals.join(', ')}]`);
  }
  if (variants.length === 0) throw new Error(`No JSON type for ${name}`);
  return [...new Set(variants)].join(' | ');
}

function pythonObject(type, hint, state) {
  const index = type.getStringIndexType();
  if (index) return `dict[str, ${pythonType(index, `${hint}Value`, state)}]`;
  if (state.names.has(type)) return state.names.get(type);
  const alias = type.aliasSymbol;
  const base = alias?.declarations?.some((node) => node.getSourceFile().fileName === source) ? alias.name : hint;
  let name = base;
  for (let suffix = 2; state.definitions.has(name); suffix++) name = `${base}${suffix}`;
  state.definitions.set(name, '');
  state.names.set(type, name);
  const fields = type.getProperties().map((property) => pythonField(name, property, state));
  const definition = fields.some(([key]) => !/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(key))
    ? `${name} = TypedDict(\n    "${name}",\n    {\n${fields.map(([key, annotation]) => `        ${JSON.stringify(key)}: ${annotation},`).join('\n')}\n    },\n)`
    : `class ${name}(TypedDict):\n${fields.map(([key, annotation]) => `    ${key}: ${annotation}`).join('\n') || '    pass'}`;
  state.definitions.delete(name);
  state.definitions.set(name, definition);
  return name;
}

function pythonField(parent, property, state) {
  const key = property.getName();
  const name = `${parent === 'ResolvedConfig' ? '' : parent}${typeName(key)}`;
  const type = state.checker.getTypeOfSymbol(property);
  const optional = (property.flags & ts.SymbolFlags.Optional) !== 0;
  const annotation = pythonType(type, name, state);
  return [key, optional ? `NotRequired[${annotation}]` : annotation];
}
